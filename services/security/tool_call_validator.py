"""Schema and safety validation of model-generated tool calls, SQL and code (NIST Protect).

Nothing generated by the model (or derived from untrusted text) is executed without
passing through this module first:

- Tool calls: strict allowlist + Pydantic schema per tool (extra fields forbidden),
  read-only enforcement for the support agent and rejection of injection payloads in
  arguments. Critical tools (approve returns, confirm dispatch, change carrier, share
  B2B data) are never executed directly: they are flagged `requires_human_approval`
  and must go through `services.security.hitl.approval_gate`.
- SQL: only a single read-only `SELECT` without comments, stacked statements or
  dangerous functions is accepted.
- Code: the agent has no code-execution capability; any request is rejected.
"""

from __future__ import annotations

import json
import logging
import re
from dataclasses import dataclass, field
from typing import Any, Dict, List, Literal, Optional, Type

from pydantic import BaseModel, ConfigDict, Field, ValidationError

logger = logging.getLogger("trackflow.security.tool_validator")

# Payload fragments that must never travel inside a tool argument
DANGEROUS_ARGUMENT_PATTERNS = [
    re.compile(r";\s*(?:drop|delete|update|insert|alter|truncate|grant|create)\b", re.I),
    re.compile(r"\b(?:union\s+select|or\s+1\s*=\s*1|xp_cmdshell)\b", re.I),
    re.compile(r"--|/\*|\*/"),
    re.compile(r"\b(?:os\.system|subprocess|eval\s*\(|exec\s*\(|__import__)", re.I),
    re.compile(r"\$\(|`[^`]+`|\|\s*(?:sh|bash)\b"),
    re.compile(r"\.\./"),
]


class ManageIncidentsReadArgs(BaseModel):
    """Support agent may only read incidents."""

    model_config = ConfigDict(extra="forbid")
    action: Literal["get"]
    incident_id: str = Field(..., min_length=1, max_length=256)


class QueryInventoryReadArgs(BaseModel):
    """Support agent may only read inventory."""

    model_config = ConfigDict(extra="forbid")
    query: str = Field(..., min_length=1, max_length=500)
    warehouse: Optional[Literal["LA", "ZGZ", "los_angeles", "zaragoza"]] = None
    action: Literal["read"] = "read"
    mutate: Literal[False] = False


TOOL_SCHEMAS: Dict[str, Type[BaseModel]] = {
    "manage_incidents": ManageIncidentsReadArgs,
    "query_inventory": QueryInventoryReadArgs,
}

# Tools with irreversible impact: only proposable, executed after HITL approval
CRITICAL_TOOLS: Dict[str, str] = {
    "approve_return": "return_approval",
    "confirm_dispatch": "high_value_dispatch",
    "change_carrier": "carrier_change",
    "share_brand_data": "cross_brand_data_share",
    "delete_data": "data_deletion",
    "send_external_message": "external_send",
}


@dataclass
class ToolCallValidation:
    """Outcome of validating a proposed tool call."""

    allowed: bool
    tool_name: str
    arguments: Dict[str, Any] = field(default_factory=dict)
    requires_human_approval: bool = False
    critical_action_type: Optional[str] = None
    errors: List[str] = field(default_factory=list)


def _scan_arguments(arguments: Dict[str, Any]) -> List[str]:
    errors: List[str] = []
    for key, value in arguments.items():
        if isinstance(value, str):
            for pattern in DANGEROUS_ARGUMENT_PATTERNS:
                if pattern.search(value):
                    errors.append(f"Argumento '{key}' contiene un patrón peligroso ({pattern.pattern}).")
                    break
    return errors


def validate_tool_call(tool_name: str, arguments: Dict[str, Any] | str) -> ToolCallValidation:
    """Validate a tool call proposed by the model before any execution."""
    if isinstance(arguments, str):
        try:
            arguments = json.loads(arguments)
        except json.JSONDecodeError:
            return ToolCallValidation(False, tool_name, errors=["Argumentos no son JSON válido."])
    if not isinstance(arguments, dict):
        return ToolCallValidation(False, tool_name, errors=["Argumentos deben ser un objeto JSON."])

    if tool_name in CRITICAL_TOOLS:
        result = ToolCallValidation(
            allowed=False,
            tool_name=tool_name,
            arguments=arguments,
            requires_human_approval=True,
            critical_action_type=CRITICAL_TOOLS[tool_name],
            errors=["Acción crítica: debe enviarse al flujo HITL, no ejecutarse directamente."],
        )
        logger.warning("[TOOL_VALIDATION] tool=%s decision=requires_hitl", tool_name)
        return result

    schema = TOOL_SCHEMAS.get(tool_name)
    if schema is None:
        logger.warning("[TOOL_VALIDATION] tool=%s decision=blocked reason=not_allowlisted", tool_name)
        return ToolCallValidation(False, tool_name, arguments, errors=[f"Herramienta '{tool_name}' no permitida."])

    errors = _scan_arguments(arguments)
    if errors:
        logger.warning("[TOOL_VALIDATION] tool=%s decision=blocked reason=dangerous_argument", tool_name)
        return ToolCallValidation(False, tool_name, arguments, errors=errors)

    try:
        parsed = schema.model_validate(arguments)
    except ValidationError as exc:
        msgs = [f"{'.'.join(str(p) for p in e['loc'])}: {e['msg']}" for e in exc.errors()]
        logger.warning("[TOOL_VALIDATION] tool=%s decision=blocked reason=schema errors=%s", tool_name, msgs)
        return ToolCallValidation(False, tool_name, arguments, errors=msgs)

    return ToolCallValidation(True, tool_name, parsed.model_dump())


SQL_FORBIDDEN_KEYWORDS = re.compile(
    r"\b(?:insert|update|delete|drop|alter|truncate|create|grant|revoke|merge|replace|attach|"
    r"pragma|exec|execute|call|copy|into\s+outfile|load_file|pg_sleep|sleep|benchmark)\b",
    re.I,
)


def validate_generated_sql(sql: str) -> tuple[bool, str]:
    """Allow only a single read-only SELECT statement. Returns (is_valid, reason)."""
    if not isinstance(sql, str) or not sql.strip():
        return False, "SQL vacío."
    statement = sql.strip().rstrip(";").strip()
    if ";" in statement:
        return False, "No se permiten múltiples sentencias SQL."
    if "--" in statement or "/*" in statement:
        return False, "No se permiten comentarios en SQL generado."
    if not re.match(r"^(?:select|with)\b", statement, re.I):
        return False, "Solo se permiten consultas SELECT de lectura."
    if SQL_FORBIDDEN_KEYWORDS.search(statement):
        return False, "La consulta contiene operaciones de escritura o funciones prohibidas."
    return True, "ok"


def validate_generated_code(_code: str) -> tuple[bool, str]:
    """The support agent never executes model-generated code."""
    return False, "La ejecución de código generado por el modelo está deshabilitada por política."
